/// của app), từ loại, câu ví dụ + dịch, và mẹo phát âm cho những từ hay bị
/// đọc sai (âm câm, trọng âm đổi theo từ loại, từ đồng âm dễ nhầm). Dùng cho
/// thẻ từ vựng xoay vòng ở màn chờ (`presentation/screens/boot/boot_screen.dart`).
///
/// Quy ước IPA: dấu ˈ đặt TRƯỚC âm tiết nhấn chính, ˌ trước âm tiết nhấn phụ,
/// dấu chấm tách âm tiết (giống từ điển Cambridge).
library;

class ToeicWord {
  final String word;
  final String ipa;

  /// n / v / adj / adv / phr / prep - xem [typeLabel].
  final String type;
  final String meaning;
  final String example;
  final String exampleVi;

  /// Mẹo phát âm/cách dùng - chỉ có ở những từ dễ sai.
  final String? tip;

  const ToeicWord(this.word, this.ipa, this.type, this.meaning, this.example, this.exampleVi, {this.tip});

  String get typeLabel => switch (type) {
        'n' => 'danh từ',
        'v' => 'động từ',
        'adj' => 'tính từ',
        'adv' => 'trạng từ',
        'prep' => 'giới từ',
        _ => 'cụm từ',
      };
}

